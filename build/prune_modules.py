"""Prune Debian's module tree to `build/modules.allow` and its dependency closure.

Debian's `linux-image-amd64` ships **4229 modules** and this appliance binds three device classes.
Everything outside the closure is deleted, `modules.dep` is regenerated from what is left, and
`build/verify.py` fails the build if anything survives that should not have.

The interesting half is a pure function — `closure(dependencies, wanted)` — so the suite can feed
it a graph with a cycle, a missing name and a name that resolves two ways, none of which is
convenient to arrange with a real kernel tree. The filesystem half is the thin part below it.

    python3 build/prune_modules.py --tree <dir> --allow build/modules.allow \\
        --write-loadlist <path>
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Iterable
from pathlib import Path


class PruneError(Exception):
    """The module tree does not say what the allowlist assumes."""


def module_name(path: str) -> str:
    """`kernel/drivers/hid/hid-generic.ko.xz` -> `hid_generic`.

    Two normalisations in one line, and both bite. The extension is `.ko`, `.ko.xz` or `.ko.zst`
    depending on how the distribution compresses modules, and **the filename uses hyphens where
    the module name uses underscores** — `hid-generic.ko.xz` is the module `hid_generic`. An
    allowlist written against filenames would silently match nothing for exactly the drivers that
    matter most here.
    """
    stem = path.rsplit("/", 1)[-1]
    for suffix in (".ko.xz", ".ko.zst", ".ko.gz", ".ko"):
        if stem.endswith(suffix):
            stem = stem[: -len(suffix)]
            break
    return stem.replace("-", "_")


def parse_modules_dep(text: str) -> dict[str, list[str]]:
    """`modules.dep` as `{module name: [dependency names]}`.

    The file's own form is `path/to/mod.ko: path/to/dep.ko path/to/other.ko`, paths relative to the
    version directory. Names rather than paths come out of here because that is what the allowlist
    is written in and what `modprobe` is given.
    """
    graph: dict[str, list[str]] = {}
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        target, separator, rest = line.partition(":")
        if not separator:
            raise PruneError(f"modules.dep:{number}: no ':' in {line!r}")
        graph[module_name(target)] = [module_name(dep) for dep in rest.split()]
    return graph


def closure(graph: dict[str, list[str]], wanted: Iterable[str]) -> set[str]:
    """Every module needed to load `wanted`, including `wanted` itself.

    **A name that is not in the graph is not an error here**, and that is deliberate rather than
    lax: `build/modules.allow` names host controllers a given kernel may have built in, and a
    machine whose `xhci_pci` is `=y` has nothing to load and nothing missing. What *would* be an
    error — an allowlist that resolves to nothing at all — is checked by the caller, where the
    message can say so.

    Cycles are handled by construction. `modules.dep` is a DAG in practice and this does not rely
    on that.
    """
    found: set[str] = set()
    pending = list(wanted)
    while pending:
        name = pending.pop()
        if name in found:
            continue
        found.add(name)
        pending.extend(graph.get(name, ()))
    return found


def parse_allowlist(text: str) -> list[str]:
    """One module name per line, `#` comments and blank lines ignored."""
    names = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            names.append(line.replace("-", "_"))
    if not names:
        raise PruneError("the allowlist is empty; every module would be deleted")
    return names


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tree", required=True, type=Path)
    parser.add_argument("--allow", required=True, type=Path)
    parser.add_argument("--write-loadlist", required=True, type=Path)
    args = parser.parse_args(argv)

    dep_file = args.tree / "modules.dep"
    if not dep_file.is_file():
        raise PruneError(
            f"{dep_file} does not exist. Debian does not ship modules.dep in the .deb — it is "
            "generated by the maintainer script, and this build runs none. Run depmod first."
        )

    graph = parse_modules_dep(dep_file.read_text(encoding="utf-8"))
    wanted = parse_allowlist(args.allow.read_text(encoding="utf-8"))
    keep = closure(graph, wanted)

    resolved = sorted(keep & set(graph))
    if not resolved:
        raise PruneError(
            f"none of {wanted} exists in this kernel's module tree. Either the allowlist names "
            "modules from a different kernel, or depmod ran against the wrong directory."
        )

    removed = 0
    kept = 0
    for path in sorted(args.tree.rglob("*.ko*")):
        if module_name(str(path)) in keep:
            kept += 1
            continue
        path.unlink()
        removed += 1

    # Empty directories left behind are not a claim either way, but a tree full of them makes
    # `find kernel/net` answer "exists" to a person checking the network claim by hand.
    for directory in sorted(args.tree.rglob("*"), key=lambda p: len(p.parts), reverse=True):
        if directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()

    # What `build/init` loads, in dependency order left to modprobe. Only the names that actually
    # resolved: asking for a module this kernel builds in would print a scary line on every boot.
    args.write_loadlist.parent.mkdir(parents=True, exist_ok=True)
    args.write_loadlist.write_text(
        "\n".join(name for name in wanted if name in graph) + "\n", encoding="utf-8"
    )

    builtin = [name for name in wanted if name not in graph]
    print(f"modules: kept {kept}, removed {removed}, closure {len(resolved)}")
    if builtin:
        print(f"modules: not loadable modules in this kernel (built in or absent): {builtin}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except PruneError as error:
        print(f"prune-modules: {error}", file=sys.stderr)
        sys.exit(1)
